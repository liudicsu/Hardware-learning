// Width estimate: CJK and full-width forms take one em, everything else 0.6 em.
function textWidth(s, size) {
  let w = 0;
  for (const ch of s) w += /[\u3000-\u9fff\uff00-\uffef]/.test(ch) ? size : 0.6 * size;
  return w;
}
const hasCjk = (s) => /[\u4e00-\u9fff]/.test(s);
const lines = (s) => s.split("\n");

function checkText(where, text, { mono = false } = {}) {
  if (text === undefined) return;
  if (typeof text === "string") {
    // A shared string must be language-neutral: identifiers, numbers, units.
    ok(mono || !/[a-z]{3,}/.test(text.replace(/\b(Hz|ms|µs)\b/g, "")), `${where}: "${text}" is English prose; give { zh, en }`);
    return;
  }
  ok(text.zh && text.en, `${where}: both zh and en are required`);
  ok(hasCjk(text.zh), `${where}: zh label "${text.zh}" has no Chinese`);
}
const variants = (t) => (t === undefined ? [] : typeof t === "string" ? [t] : [t.zh, t.en]);

// ---------- circuit diagrams ----------
const TWO_TERMINAL = new Set(["switch", "button", "resistor", "motor"]);
function terminals(p) {
  const half = (p.len ?? 36) / 2;
  const [x, y] = p.at;
  return p.dir === "h" ? [[x - half, y], [x + half, y]] : [[x, y - half], [x, y + half]];
}
function distToSeg([px, py], [ax, ay], [bx, by]) {
  const dx = bx - ax, dy = by - ay;
  const l2 = dx * dx + dy * dy;
  const t = l2 ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / l2)) : 0;
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}
function textBox(text, at, anchor, size) {
  const ls = lines(text);
  const w = Math.max(...ls.map((l) => textWidth(l, size)));
  const x0 = anchor === "start" ? at[0] : anchor === "end" ? at[0] - w : at[0] - w / 2;
  return [x0, at[1] - size, x0 + w, at[1] + 3 + (ls.length - 1) * (SUB + 3)];
}
function checkCircuit(spec, tag) {
  ok(spec.w <= NARROW_MAX, `${tag}: width ${spec.w} > ${NARROW_MAX}`);
  const inside = (x, y, what) => ok(x >= 0 && y >= 0 && x <= spec.w && y <= spec.h, `${tag}: ${what} at (${x.toFixed(0)}, ${y.toFixed(0)}) is outside ${spec.w}x${spec.h}`);
  const ids = new Map();
  for (const p of spec.parts) { ok(!ids.has(p.id), `${tag}: duplicate part/wire id ${p.id}`); ids.set(p.id, p); }
  for (const w of spec.wires) { ok(!ids.has(w.id), `${tag}: duplicate part/wire id ${w.id}`); ids.set(w.id, w); }
  for (const p of spec.parts) {
    checkText(`${tag} part ${p.id}`, p.label, p);
    inside(p.at[0], p.at[1], `part ${p.id}`);
    if (TWO_TERMINAL.has(p.type)) for (const t of terminals(p)) inside(t[0], t[1], `part ${p.id} terminal`);
    if (p.type === "box") inside(p.at[0] + p.size[0], p.at[1] + p.size[1], `box ${p.id}`);
    if (p.label) {
      ok(p.labelAt, `${tag}: part ${p.id} label has no position`);
      if (p.labelAt) for (const t of variants(p.label)) {
        const [x0, y0, x1, y1] = textBox(t, p.labelAt, p.anchor ?? "middle", p.type === "text" ? SUB : FONT);
        inside(x0, y0, `part ${p.id} label "${t}"`); inside(x1, y1, `part ${p.id} label "${t}"`);
      }
    }
  }
  for (const w of spec.wires) for (const [x, y] of w.pts) inside(x, y, `wire ${w.id} point`);
  checkNumbers(spec, tag);
  ok(spec.states.length > 0, `${tag}: no states`);
  for (const st of spec.states) {
    const sw = `${tag} state ${st.id}`;
    checkText(`${sw} label`, st.label); checkText(`${sw} text`, st.text); checkText(`${sw} readout`, st.readout);
    for (const c of st.closed) ok(["switch", "button"].includes(ids.get(c)?.type), `${sw}: closed "${c}" is not a switch or button`);
    for (const h of st.hidden ?? []) ok(ids.has(h), `${sw}: hidden "${h}" does not exist`);
    if (st.readout) {
      ok(spec.readoutAt, `${tag}: readout without readoutAt`);
      if (spec.readoutAt) for (const t of variants(st.readout)) {
        const ls = lines(t), w = Math.max(...ls.map((l) => textWidth(l, FONT)));
        inside(spec.readoutAt[0] - w / 2, spec.readoutAt[1] - FONT, `${st.id} readout "${t}"`);
        inside(spec.readoutAt[0] + w / 2, spec.readoutAt[1] + 3 + (ls.length - 1) * (FONT + 3), `${st.id} readout "${t}"`);
      }
    }
    if (!st.flow) continue;
    // the current path may only run over drawn wires, resistors/motors, and closed switches/buttons
    const hidden = new Set(st.hidden ?? []), closed = new Set(st.closed);
    const segs = [];
    for (const w of spec.wires) if (!hidden.has(w.id)) for (let i = 1; i < w.pts.length; i++) segs.push([w.pts[i - 1], w.pts[i]]);
    for (const p of spec.parts) {
      if (hidden.has(p.id) || !TWO_TERMINAL.has(p.type)) continue;
      if ((p.type === "switch" || p.type === "button") && !closed.has(p.id)) continue;
      segs.push(terminals(p));
    }
    let bad = null;
    for (let i = 1; i < st.flow.length && !bad; i++) {
      const [a, b] = [st.flow[i - 1], st.flow[i]];
      const n = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1])));
      for (let k = 0; k <= n; k++) {
        const pt = [a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n];
        if (!segs.some(([s0, s1]) => distToSeg(pt, s0, s1) <= 0.6)) { bad = pt; break; }
      }
    }
    ok(!bad, `${sw}: current path leaves the circuit (or crosses an open switch) at (${bad?.map((v) => v.toFixed(1)).join(", ")})`);
    // where the path starts and ends: supply → ground, or (with a stated reason) a closed loop away from the supplies
    const same = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1]) <= 0.6;
    const onFlow = (pt) => st.flow.some((q, i) => i > 0 && distToSeg(pt, st.flow[i - 1], q) <= 0.6);
    const supplies = spec.parts.filter((p) => p.type === "supply" && !hidden.has(p.id));
    const grounds = spec.parts.filter((p) => p.type === "ground" && !hidden.has(p.id));
    const first = st.flow[0], last = st.flow[st.flow.length - 1];
    if (st.loopReason) {
      ok(same(first, last), `${sw}: loop path (loopReason) must end where it starts`);
      ok(!supplies.some((p) => onFlow(p.at)), `${sw}: loop path (loopReason) must not touch a supply`);
    } else {
      ok(supplies.some((p) => same(p.at, first)), `${sw}: current path must start at a supply`);
      ok(grounds.some((p) => same(p.at, last)), `${sw}: current path must end at a ground`);
    }
    // every closed switch or button carries the current: both terminals lie on the path
    for (const c of st.closed) {
      const p = ids.get(c);
      if (p && TWO_TERMINAL.has(p.type)) ok(terminals(p).every(onFlow), `${sw}: closed ${c} is not on the current path`);
    }
  }
}

// ---------- timing diagrams (drawn by TimingSvg; layout constants read from Timing.tsx) ----------
const timingSrc = readFileSync(join(root, "src/components/diagrams/Timing.tsx"), "utf8");
const tconst = (name) => Number(timingSrc.match(new RegExp(`const ${name} = ([\\d.]+)`))[1]);
const T = { LEFT: tconst("LEFT"), COL: tconst("COL"), AVG_PAD: tconst("AVG_PAD"), MIN_SCALE: tconst("MIN_SCALE"), SLOPE: tconst("SLOPE") };
// inner width of a diagram box on a 390 px phone (page and figure padding), measured with Playwright
const PHONE_BOX = 332;
const CELL_PAD = 2; // clear space on each side of a row cell, viewBox units
const BUS_PAD = 4; // clear space between a bus value and its hexagon's edges, viewBox units

// Sequences pinned to an external reference that the repository cannot hold, compared field by field.
const PINNED = {
  // MPU-6000/MPU-6050 Product Specification rev 3.4, §9.3 "Single-Byte Read Sequence":
  //   master: S AD+W     RA     S AD+R          NACK P
  //   slave:          ACK    ACK          ACK DATA
  // (AD+W and AD+R are drawn as the address and the R/W bit in separate columns; Sr is the repeated S.)
  "i2c-read-who-am-i": {
    SDA: ["S", "0x68", "W", "ACK", "0x75", "ACK", "Sr", "0x68", "R", "ACK", "0x68", "NACK", "P"],
    from: ["Uno", "Uno", "Uno", "MPU", "Uno", "MPU", "Uno", "Uno", "Uno", "MPU", "MPU", "Uno", "Uno"],
  },
};
function checkPinned(spec, tag) {
  const pin = PINNED[spec.id];
  if (!pin) return;
  const en = (t) => (typeof t === "string" ? t : t.en);
  for (const [name, want] of Object.entries(pin)) {
    const sig = spec.signals.find((s) => en(s.name) === name);
    const row = (spec.rows ?? []).find((r) => en(r.name) === name);
    const got = sig ? (sig.values ?? sig.levels).map(en) : row ? row.cells.map(en) : null;
    ok(got !== null, `${tag}: pinned signal/row "${name}" missing`);
    if (got) ok(JSON.stringify(got) === JSON.stringify(want), `${tag}: "${name}" is ${JSON.stringify(got)}, the reference says ${JSON.stringify(want)}`);
  }
}
function checkNumbers(spec, tag) {
  for (const n of spec.numbers ?? []) {
    const hit = Math.abs(n.value - n.expect) <= n.tol;
    ok(hit, `${tag}: number ${n.note}: computed ${n.value} vs lesson ${n.expect} (tol ${n.tol})`);
    if (hit) console.log(`calc  ${spec.id}: ${n.note}: ${+n.value.toFixed(4)} ≈ ${+n.expect.toFixed(4)}`);
  }
}
const sum = (xs) => xs.reduce((a, b) => a + b, 0);
/** Column widths in viewBox units for the columns a..b drawn as one line (Timing.tsx columnEdges). */
function colWidths(spec, [a, b]) {
  const cols = spec.columns ? spec.columns.slice(a, b + 1) : Array(b - a + 1).fill(1);
  const unit = spec.columnScale ?? (cols.length * T.COL) / sum(cols);
  return cols.map((w) => w * unit);
}
function checkTiming(spec, tag) {
  const lens = [
    ...(spec.columns ? [spec.columns.length] : []),
    ...spec.signals.map((s) => (s.kind === "bus" ? s.values?.length ?? 0 : s.levels?.length ?? 0)),
    ...(spec.rows ?? []).map((r) => r.cells.length),
  ];
  const n = Math.max(1, ...lens);
  ok(lens.every((l) => l === n), `${tag}: columns, levels/values and row cells must all have ${n} entries (got ${lens.join(", ")})`);
  for (const w of spec.columns ?? []) ok(w > 0, `${tag}: column width ${w} must be > 0`);
  ok(spec.columnScale === undefined || spec.columnScale > 0, `${tag}: columnScale must be > 0`);
  const hasAvg = spec.signals.some((s) => s.average);
  const lineW = (r) => T.LEFT + sum(colWidths(spec, r)) + 8 + (hasAvg ? T.AVG_PAD : 0);

  // line layout: "lines" cover every column in order; "narrowLines" (below 640 px) may leave columns out
  const wide = spec.lines ?? [[0, n - 1]];
  const narrow = spec.narrowLines ?? wide;
  const inRange = (r) => Array.isArray(r) && r[0] >= 0 && r[1] < n && r[0] <= r[1];
  wide.forEach((r, k) => ok(inRange(r) && r[0] === (k ? wide[k - 1][1] + 1 : 0), `${tag}: lines[${k}] ${JSON.stringify(r)} must continue the previous line`));
  ok(wide[wide.length - 1][1] === n - 1, `${tag}: lines must end at column ${n - 1}`);
  narrow.forEach((r, k) => ok(inRange(r) && (k === 0 || r[0] > narrow[k - 1][1]), `${tag}: narrowLines[${k}] ${JSON.stringify(r)} out of range or order`));
  const lineOf = (set, c) => set.find((r) => c >= r[0] && c <= r[1]);

  // text size: Timing.tsx's smallest text is 14 units (spans, averages, axis); it must render at >= 12 px
  // on a 390 px phone (narrow lines in a 332 px box) and at 640 px (wide lines in a 582 px box);
  // the line boxes are capped at 1.3 px per unit (TimingDiagram.tsx).
  const pxAt = (set, box) => { const w = Math.max(...set.map(lineW)); return { w, px: 14 * Math.min(1.3, box / w) }; };
  for (const [name, set, box] of [["390 px", narrow, PHONE_BOX], ["640 px", wide, PHONE_BOX + 250]]) {
    const { w, px } = pxAt(set, box);
    ok(px >= 12, `${tag}: at ${name} the ${w.toFixed(0)}-unit line renders the smallest text at ${px.toFixed(1)} px (< 12)`);
    ok(w * T.MIN_SCALE <= box, `${tag}: at ${name} a ${w.toFixed(0)}-unit line would scroll`);
  }

  for (const [k, s] of spec.signals.entries()) {
    const st = `${tag} signal ${k}`;
    checkText(`${st} name`, s.name, { mono: true });
    for (const t of variants(s.name)) ok(textWidth(t, 18) <= T.LEFT - 12, `${st}: name "${t}" wider than the label column`);
    if (s.kind === "bus") for (const v of s.values ?? []) checkText(`${st} value`, v, { mono: true });
    else for (const lv of s.levels ?? []) ok(typeof lv === "number" || lv === "x" || lv === "z", `${st}: bad level ${lv}`);
    if (s.average) {
      ok(s.kind !== "bus", `${st}: average on a bus signal`);
      ok(s.average.level >= 0 && s.average.level <= 1, `${st}: average level ${s.average.level} outside 0..1`);
      checkText(`${st} average`, s.average.label, { mono: true });
      for (const t of variants(s.average.label)) ok(textWidth(t, 14) <= T.AVG_PAD - 4, `${st}: average label "${t}" wider than ${T.AVG_PAD - 4}`);
    }
  }
  for (const r of spec.rows ?? []) {
    checkText(`${tag} row name`, r.name, { mono: true });
    for (const t of variants(r.name)) ok(textWidth(t, 15) <= T.LEFT - 12, `${tag}: row name "${t}" wider than the label column`);
    for (const c of r.cells) checkText(`${tag} row cell`, c, { mono: true });
  }
  // per drawn line: bus values fit their bands, row cells their columns, spans and axis label the line
  for (const [setName, set] of [["lines", wide], ["narrowLines", narrow]]) {
    for (const r of set) {
      const cw = colWidths(spec, r);
      const w = lineW(r);
      for (const [k, s] of spec.signals.entries()) {
        if (s.kind !== "bus") continue;
        for (const loc of ["zh", "en"]) {
          const vals = s.values.slice(r[0], r[1] + 1).map((v) => (typeof v === "string" ? v : v[loc]));
          for (let i = 0; i < vals.length; ) {
            let j = i;
            while (j + 1 < vals.length && vals[j + 1] === vals[i]) j++;
            const bw = sum(cw.slice(i, j + 1));
            // the flat top of the band minus BUS_PAD on each side
            const room = bw - 2 * Math.min(T.SLOPE, bw / 4) - 2 * BUS_PAD;
            if (vals[i] && vals[i] !== "x") ok(textWidth(vals[i], 16) <= room, `${tag} ${setName} ${JSON.stringify(r)} signal ${k}: "${vals[i]}" (${textWidth(vals[i], 16).toFixed(0)}) wider than the ${room.toFixed(0)} units inside its band (padding ${BUS_PAD})`);
            i = j + 1;
          }
        }
      }
      for (const row of spec.rows ?? [])
        for (let i = r[0]; i <= r[1]; i++)
          for (const t of variants(row.cells[i])) ok(textWidth(t, 17) <= cw[i - r[0]] - 2 * CELL_PAD, `${tag} ${setName}: row cell "${t}" needs more than its ${cw[i - r[0]].toFixed(0)}-unit column minus ${CELL_PAD} on each side`);
      if (spec.axisLabel) for (const t of variants(spec.axisLabel)) ok(textWidth(t, 14) <= sum(cw), `${tag} ${setName}: axis label "${t}" wider than the time axis`);
      for (const sp of spec.spans ?? []) {
        if (sp.from < r[0] || sp.to > r[1]) continue;
        const x0 = T.LEFT + sum(cw.slice(0, sp.from - r[0]));
        const x1 = x0 + sum(cw.slice(sp.from - r[0], sp.to - r[0] + 1));
        for (const t of variants(sp.label)) {
          const tw = textWidth(t, 14);
          ok((x0 + x1) / 2 - tw / 2 >= 0 && (x0 + x1) / 2 + tw / 2 <= w, `${tag} ${setName}: span label "${t}" (${tw.toFixed(0)}) runs outside the ${w.toFixed(0)}-unit line`);
        }
      }
    }
  }
  for (const sp of spec.spans ?? []) {
    ok(sp.from >= 0 && sp.to < n && sp.from <= sp.to, `${tag}: span ${sp.from}..${sp.to} outside 0..${n - 1}`);
    checkText(`${tag} span`, sp.label);
    const l = lineOf(wide, sp.from);
    ok(l && sp.to <= l[1], `${tag}: span ${sp.from}..${sp.to} crosses a line break`);
    const nl = lineOf(narrow, sp.from);
    ok(nl ? sp.to <= nl[1] : !narrow.some((r) => r[0] <= sp.to && r[1] >= sp.from), `${tag}: span ${sp.from}..${sp.to} is cut by narrowLines`);
  }
  for (const [k, st] of (spec.steps ?? []).entries()) {
    checkText(`${tag} step ${k + 1}`, st.label);
    if (st.column !== undefined) {
      ok(st.column >= 0 && st.column < n, `${tag} step ${k + 1}: column ${st.column} outside 0..${n - 1}`);
      ok(!!lineOf(narrow, st.column), `${tag} step ${k + 1}: column ${st.column} is not drawn below 640 px`);
    }
    for (const i of st.signals ?? []) ok(i >= 0 && i < spec.signals.length, `${tag} step ${k + 1}: signal ${i} does not exist`);
  }
  checkNumbers(spec, tag);
  checkPinned(spec, tag);
}

/**
 * Optional `script: { run, lines }`: run `python3 run` from the script's folder and require each line in its output.
 * A missing script or one that exits with an error is a FAIL line, not a crash.
 */
function checkScript(spec, tag) {
  if (!spec.script) return;
  const path = join(root, spec.script.run);
  if (!existsSync(path)) { fail(`${tag}: script ${spec.script.run} missing`); return; }
  let out;
  try {
    out = execFileSync("python3", [path], { encoding: "utf8", cwd: dirname(path), stdio: ["ignore", "pipe", "pipe"] });
  } catch (e) {
    const err = String(e.stderr || e.message).trim().split("\n").pop();
    fail(`${tag}: script ${spec.script.run} failed (exit ${e.status ?? "?"}): ${err}`);
    return;
  }
  for (const line of spec.script.lines) {
    const hit = out.split("\n").includes(line);
    ok(hit, `${tag}: "${line}" is not a line of the output of ${spec.script.run}`);
    if (hit) console.log(`run   ${spec.id}: "${line}"  [${spec.script.run}]`);
  }
}

/**
 * Block diagrams, optional `bindings`: the text of a node (label and sub), a step or the caption, in both languages,
 * must match every regular expression in `has` and none in `lacks`; an edge can be required to be dashed. Specs build these from the
 * same constants as their facts, so the drawing cannot drift from the lesson.
 */
function checkBindings(spec, tag, nodeIds, edgeIds) {
  for (const b of spec.bindings ?? []) {
    if (b.edge) {
      ok(edgeIds.has(b.edge), `${tag}: binding for unknown edge "${b.edge}"`);
      const e = spec.edges.find((x) => x.id === b.edge);
      if (e && b.dashed !== undefined) ok(!!e.dashed === b.dashed, `${tag}: edge ${b.edge} must be ${b.dashed ? "dashed" : "solid"} (${b.note})`);
      continue;
    }
    // what the binding looks at: a node's label + sub, a step's text (1-based) or the caption
    let where, get;
    if (b.node) {
      ok(nodeIds.has(b.node), `${tag}: binding for unknown node "${b.node}"`);
      const n = spec.nodes.find((x) => x.id === b.node);
      if (!n) continue;
      where = `node ${b.node}`;
      get = (pick) => `${pick(n.label)}\n${pick(n.sub)}`;
    } else if (b.step) {
      const st = (spec.steps ?? [])[b.step - 1];
      ok(st, `${tag}: binding for unknown step ${b.step}`);
      if (!st) continue;
      where = `step ${b.step}`;
      get = (pick) => pick(st.label);
    } else if (b.caption) {
      where = "caption";
      get = (pick) => pick(spec.caption);
    } else { fail(`${tag}: binding names no node, edge, step or caption`); continue; }
    for (const loc of ["zh", "en"]) {
      const pick = (t) => (t === undefined ? "" : typeof t === "string" ? t : t[loc]);
      const text = get(pick);
      for (const h of b.has ?? []) {
        const re = pick(h);
        ok(new RegExp(re).test(text), `${tag}: ${where} (${loc}) must show /${re}/ (${b.note})`);
      }
      for (const l of b.lacks ?? []) {
        const re = pick(l);
        ok(!new RegExp(re).test(text), `${tag}: ${where} (${loc}) must not show /${re}/ (${b.note})`);
      }
    }
    if (!(b.has ?? []).length && !(b.lacks ?? []).length) fail(`${tag}: binding for ${where} checks nothing`);
  }
}

/** Block diagrams, optional `flows`: in both layouts the edge starts on `from`'s box and its arrowhead ends on `to`'s. */
function checkFlows(spec, tag) {
  const onBox = ([x, y], [bx, by, bw, bh]) => x >= bx - 3 && x <= bx + bw + 3 && y >= by - 3 && y <= by + bh + 3;
  for (const f of spec.flows ?? []) {
    const e = spec.edges.find((x) => x.id === f.edge);
    ok(e && e.arrow !== false, `${tag}: flow edge ${f.edge} missing or has no arrowhead`);
    for (const which of ["wide", "narrow"]) {
      const L = spec.layouts[which], g = L.edges[f.edge], a = L.nodes[f.from], b = L.nodes[f.to];
      ok(g && a && b, `${tag} ${which}: flow ${f.edge} ${f.from} -> ${f.to} names a missing edge or node`);
      if (!(g && a && b)) continue;
      ok(onBox(g.pts[0], a) && onBox(g.pts.at(-1), b) && !onBox(g.pts.at(-1), a),
        `${tag} ${which}: edge ${f.edge} must run from ${f.from} to ${f.to} (${f.note}), runs ${JSON.stringify(g.pts[0])} -> ${JSON.stringify(g.pts.at(-1))}`);
    }
  }
}

