  ok(quadPx >= MIN_PX, `Quadrature.tsx: the ${quadW}-unit diagram renders 14-unit text at ${quadPx.toFixed(1)} px on a 390 px phone (< ${MIN_PX})`);
  const centre = T.LEFT + 4 * quadCol;
