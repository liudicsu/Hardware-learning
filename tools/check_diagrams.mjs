//  - every spec is registered, ids are unique, and every <Diagram id> in the lessons exists;
//  - zh.mdx and en.mdx of a lesson use the same diagrams in the same order;
//  - every label exists in both languages and the Chinese label contains Chinese text;
//  - both layouts place every node and edge inside the viewBox, labels fit their boxes, and every text renders
//    at >= 12 px: the narrow layout (and a circuit) fits the 332 px box of a 390 px phone, the wide one the
//    734 px box at 1280 px;
//  - timing specs (kind "timing"): equal column counts, line ranges, label, band and cell widths, and the
