// ---------- pose graphs (kind "poseGraph", drawn by PoseGraph.tsx) ----------
const PG_SRC = readFileSync(join(root, "src/components/diagrams/PoseGraph.tsx"), "utf8");
const pgConst = (name) => Number(PG_SRC.match(new RegExp(`export const ${name} = ([\\d.]+)`))[1]);
const PG = { SCALE: pgConst("PG_SCALE"), PAD: pgConst("PG_PAD"), FONT: pgConst("PG_FONT") };
function checkPoseGraph(spec, tag) {
  const { estimate: E, corrected: C, truth: T } = spec;
  const n = E.length - 1;
  ok(C.length === E.length && T.length === E.length, `${tag}: estimate, corrected and truth need the same length`);
  ok(E[0].x === 0 && E[0].y === 0 && E[0].th === 0, `${tag}: node 0 must be the origin`);
  // Which scans become nodes: SLAM Toolbox 2.8.5 (pinned in examples/month-4/pixi.lock), defaults for every
  // parameter slam.yaml does not set. Source lines (github.com/SteveMacenski/slam_toolbox, tag 2.8.5, commit ec8f763):
  //  - src/slam_toolbox_common.cpp:413 check_min_dist_and_heading_precisely defaults to false;
  //    :807 then a scan is dropped when dist^2 < 0.8 * minimum_travel_distance^2 (base pose, straight line);
  //    :400-411 minimum_time_interval defaults to transform_timeout's 0.5 s. The first callback passes via the
  //    first_measurement_ branch; callbacks 2-4 are dropped (第 1 次回调走 first_measurement_ 分支直接通过，第 2–4 次被丢弃):
  //    :769 scan_ctr++ runs before :795
  //    scan_ctr < 5, so callbacks 2-4 are dropped; callback 1 already passed via first_measurement_ (:771-777, before
  //    every other test, sets last_pose), so node 0 is the first scan. Karto keeps it: no last scan (Mapper.cpp:3150).
  //  - lib/karto_sdk/src/Mapper.cpp:3147-3178 HasMovedEnough: lidar pose turned >= minimum_travel_heading or moved
  //    >= minimum_travel_distance (minus KT_TOLERANCE 1e-6) since the last node; its time escape is 3600 s (:2118).
  const SLAM_TOOLBOX = { version: "2.8.5", factor: 0.8, minInterval: 0.5, warmup: 5 /* scan_ctr < 5 */, tolerance: 1e-6 };
  const rd = (f) => readFileSync(join(root, f), "utf8");
  const num = (text, re, what) => { const m = text.match(re); ok(m, `${tag}: ${what} not found`); return m ? Number(m[1]) : NaN; };
  const yaml = rd("examples/month-4/slam-nav/m4_nav/config/slam.yaml");
  ok(rd("examples/month-4/pixi.lock").includes(`ros-jazzy-slam-toolbox-${SLAM_TOOLBOX.version}-`), `${tag}: pixi.lock no longer pins slam_toolbox ${SLAM_TOOLBOX.version}; re-check the source lines`);
  for (const p of ["check_min_dist_and_heading_precisely", "minimum_time_interval", "transform_timeout", "throttle_scans"])
    ok(!new RegExp(`^\\s*${p}:`, "m").test(yaml), `${tag}: slam.yaml sets ${p}; the node rule assumes its default`);
  const m = spec.model;
  const want = {
    distance: num(yaml, /minimum_travel_distance:\s*([\d.]+)/, "slam.yaml minimum_travel_distance"),
    heading: num(yaml, /minimum_travel_heading:\s*([\d.]+)/, "slam.yaml minimum_travel_heading"),
    factor: SLAM_TOOLBOX.factor,
    minInterval: SLAM_TOOLBOX.minInterval,
    lidarX: num(rd("examples/month-4/urdf-tf/m4_description/urdf/robot.urdf.xacro"), /name="lidar_joint"[\s\S]*?<origin xyz="([-\d.]+) /, "URDF lidar_joint x"),
    rate: num(rd("examples/month-4/gazebo-sim/m4_gazebo/urdf/sensors.gazebo.xacro"), /name="lidar"[\s\S]*?<update_rate>([\d.]+)</, "Gazebo lidar update_rate"),
    speed: num(rd("examples/month-4/slam-nav/tour.py"), /self\.send\(min\(([\d.]+), math\.hypot/, "tour.py drive speed"),
    turnRate: num(rd("examples/month-4/slam-nav/tour.py"), /max\(-([\d.]+), min\(\1, /, "tour.py turn rate"),
  };
  ok(/<origin xyz="0 0 \$\{wheel_radius\}"\/>/.test(rd("examples/month-4/urdf-tf/m4_description/urdf/robot.urdf.xacro")), `${tag}: base_joint is no longer straight above base_footprint`);
  for (const [k, v] of Object.entries(want)) ok(m[k] === v, `${tag}: model.${k} = ${m[k]}, source says ${v}`);
  // the scans: one per lidar period, at most speed / rate apart
  const S = spec.scans;
  for (let k = 1; k < S.length; k++) {
    if (Math.abs(S[k].t - S[k - 1].t - 1 / want.rate) > 1e-9 || Math.hypot(S[k].odom.x - S[k - 1].odom.x, S[k].odom.y - S[k - 1].odom.y) > want.speed / want.rate + 1e-9) {
      fail(`${tag}: scan ${k} is not one lidar period / ${want.speed / want.rate} m after scan ${k - 1}`); break;
    }
  }
  checks++;
  // re-run the rule
  const norm = (x) => Math.atan2(Math.sin(x), Math.cos(x));
  const sq = (a, b) => (a.x - b.x) ** 2 + (a.y - b.y) ** 2;
  const lid = (p) => ({ x: p.x + want.lidarX * Math.cos(p.th), y: p.y + want.lidarX * Math.sin(p.th) });
  const expected = [0];
  let passed = S[0];
  for (let k = 1; k < S.length; k++) {
    if (k + 1 < SLAM_TOOLBOX.warmup || S[k].t - passed.t < want.minInterval) continue;
    if (sq(S[k].odom, passed.odom) < want.factor * want.distance ** 2) continue; // shouldProcessScan: distance only
    passed = S[k];
    const last = S[expected[expected.length - 1]].odom;
    if (Math.abs(norm(S[k].odom.th - last.th)) >= want.heading || sq(lid(S[k].odom), lid(last)) >= want.distance ** 2 - SLAM_TOOLBOX.tolerance) expected.push(k);
  }
  ok(JSON.stringify(spec.nodes) === JSON.stringify(expected), `${tag}: nodes ${JSON.stringify(spec.nodes)} differ from SLAM Toolbox's rule ${JSON.stringify(expected)}`);
  ok(spec.nodes.every((k, i) => E[i] === S[k].odom || JSON.stringify(E[i]) === JSON.stringify(S[k].odom)), `${tag}: estimate is not the odometry pose of each node's scan`);
  ok(spec.nodes.every((k, i) => JSON.stringify(T[i]) === JSON.stringify(S[k].truth)), `${tag}: truth is not the true pose of each node's scan`);
  // Fixed expectations, computed by hand (catches a logic error shared by the spec and the rule above):
  //  node 0 = scan 0: the first callback passes (first_measurement_) -> (0, 0, 0).
  //  node 1 = scan 8: scans 1-3 dropped (scan_ctr 2-4), scan 4 is 0.4 s after scan 0 (< 0.5 s); scan 7 is
  //    7 x 0.025 = 0.175 m out, 0.175^2 = 0.030625 < 0.8 x 0.2^2 = 0.032 -> dropped; scan 8 is 0.200 m out,
  //    0.04 >= 0.032 passes, and 0.04 >= 0.2^2 - 1e-6 for Karto -> (0.200, 0, 0).
  //  nodes 1-12 = scans 8, 16, ..., 96: the 2.4 m side takes 9.6 s = 96 scans, so node 12 is at the corner (2.4, 0).
  //  node 13 = scan 130: the turn on the spot (base does not move, every scan dropped) takes (pi/2) / 0.6 =
  //    2.61799 s and ends at t = 12.21799 s; scan 129 (t = 12.9) is 0.25 x 0.68201 = 0.17050 m from the corner
  //    (< 0.17889, dropped); scan 130 (t = 13.0) is d = 0.25 x 0.78201 = 0.19550 m out and passes; Karto keeps it
  //    because odometry turned th = 0.97 x pi/2 = 1.52367 rad >= 0.2. Position x = 2.4 + d cos th = 2.40921,
  //    y = d sin th = 0.19528.
  const HAND = [[0, 0, 0, 0], [1, 8, 0.2, 0], [12, 96, 2.4, 0], [13, 130, 2.40921, 0.19528]];
  for (const [i, k, x, y] of HAND)
    ok(spec.nodes[i] === k && Math.abs(E[i].x - x) < 5e-6 && Math.abs(E[i].y - y) < 5e-6,
      `${tag}: node ${i} should be scan ${k} at (${x}, ${y}) by hand; got scan ${spec.nodes[i]} at (${E[i]?.x.toFixed(5)}, ${E[i]?.y.toFixed(5)})`);
  console.log(`calc  ${spec.id}: ${S.length} scans -> ${expected.length} nodes by SLAM Toolbox ${SLAM_TOOLBOX.version}'s rule (drop < sqrt(${want.factor}) x ${want.distance} = ${(Math.sqrt(want.factor) * want.distance).toFixed(3)} m, then ${want.distance} m or ${want.heading} rad)`);
  // the view: one layout of at most 360 units; text >= 12 px on a phone, inside the viewBox
  const ps = [...E, ...C];
  const x0 = Math.min(...ps.map((p) => p.x)), x1 = Math.max(...ps.map((p) => p.x));
  const y0 = Math.min(...ps.map((p) => p.y)), y1 = Math.max(...ps.map((p) => p.y));
  const w = Math.ceil((x1 - x0) * PG.SCALE + 2 * PG.PAD), h = Math.ceil((y1 - y0) * PG.SCALE + 2 * PG.PAD);
  const at = (p) => [PG.PAD + (p.x - x0) * PG.SCALE, PG.PAD + (y1 - p.y) * PG.SCALE];
  ok(w <= NARROW_MAX, `${tag}: width ${w} > ${NARROW_MAX}`);
  const px = PG.FONT * Math.min(1.5, PHONE_BOX / w);
  ok(px >= 12, `${tag}: text renders at ${px.toFixed(1)} px on a 390 px phone (< 12)`);
  const [sx, sy] = at(E[0]), [bx, by] = at(E[1]), [ex, ey] = at(E[n]), [tx0, ty0] = at(T[n]);
  const pos = { start: [sx + 8, sy + 18, "start"], spacing: [(sx + bx) / 2, Math.min(sy, by) - 10, "middle"], gap: [(ex + tx0) / 2 + 10, (ey + ty0) / 2 + 4, "start"] };
  for (const [key, [x, y, a]] of Object.entries(pos)) {
    checkText(`${tag} text ${key}`, spec.text[key]);
    for (const t of variants(spec.text[key])) {
      const tw = textWidth(t, PG.FONT), xa = a === "start" ? x : x - tw / 2;
      ok(xa >= 0 && xa + tw <= w && y - PG.FONT >= 0 && y + 3 <= h, `${tag}: text "${t}" at (${xa.toFixed(0)}, ${y.toFixed(0)}) leaves ${w}x${h}`);
    }
  }
  for (const [key, t] of Object.entries(spec.legend)) checkText(`${tag} legend ${key}`, t);
  for (const [k, f] of spec.frames.entries()) {
    checkText(`${tag} frame ${k + 1}`, f.label);
    ok(f.upto >= 2 && f.upto <= n + 1, `${tag} frame ${k + 1}: upto ${f.upto} outside 2..${n + 1}`);
    if (f.match !== undefined) ok(f.match < f.upto && f.match >= spec.matchWindow, `${tag} frame ${k + 1}: match node ${f.match} must be shown and have ${spec.matchWindow} predecessors`);
    if (f.gap || f.loop) ok(f.upto === n + 1, `${tag} frame ${k + 1}: the gap and the loop closure need every node`);
  }
  checkNumbers(spec, tag);
}

// ---------- geometry figures (kind "geo", drawn by Geo2D.tsx) ----------
const GEO_SRC = readFileSync(join(root, "src/components/diagrams/Geo2D.tsx"), "utf8");
const GEO = { FONT: Number(GEO_SRC.match(/export const GEO_FONT = ([\d.]+)/)[1]), MAX: Number(GEO_SRC.match(/export const GEO_MAX_SCALE = ([\d.]+)/)[1]) };
const geoPolar = ([cx, cy], r, deg) => [cx + r * Math.sin((deg * Math.PI) / 180), cy - r * Math.cos((deg * Math.PI) / 180)];
function checkGeo(spec, tag) {
  const { w, h } = spec;
  ok(w <= NARROW_MAX, `${tag}: width ${w} > ${NARROW_MAX} (text would render below ${MIN_PX} px on a 390 px phone)`);
  const px = GEO.FONT * Math.min(GEO.MAX, PHONE_BOX_PX / w);
  ok(px >= MIN_PX, `${tag}: text renders at ${px.toFixed(1)} px on a 390 px phone`);
  const inside = (x, y, what) => ok(x >= 0 && x <= w && y >= 0 && y <= h, `${tag}: ${what} at (${x.toFixed(0)}, ${y.toFixed(0)}) leaves ${w}x${h}`);
  const byId = {};
  for (const [k, s] of spec.shapes.entries()) {
    const what = `shape ${s.id ?? k} (${s.type})`;
    if (s.id) { ok(!byId[s.id], `${tag}: duplicate shape id ${s.id}`); byId[s.id] = s; }
    if (s.type === "line") { inside(...s.from, what); inside(...s.to, what); }
    else if (s.type === "polyline") { ok(s.pts.length >= 2, `${tag}: ${what} needs 2+ points`); for (const p of s.pts) inside(...p, what); }
    else if (s.type === "rect") { inside(...s.at, what); inside(s.at[0] + s.size[0], s.at[1] + s.size[1], what); }
    else if (s.type === "circle") { inside(s.at[0] - s.r, s.at[1] - s.r, what); inside(s.at[0] + s.r, s.at[1] + s.r, what); }
    else if (s.type === "arc") for (let d = Math.min(s.from, s.to); d <= Math.max(s.from, s.to); d += 1) inside(...geoPolar(s.at, s.r, d), what);
    else if (s.type === "text") {
      checkText(`${tag} ${what}`, s.label, { mono: s.mono });
      for (const t of variants(s.label)) {
        const tw = textWidth(t, GEO.FONT), a = s.anchor ?? "middle";
        const x0 = a === "start" ? s.at[0] : a === "end" ? s.at[0] - tw : s.at[0] - tw / 2;
        inside(x0, s.at[1] - GEO.FONT, `${what} "${t}"`);
        inside(x0 + tw, s.at[1] + 3, `${what} "${t}"`);
      }
    }
  }
  const groups = new Set(spec.shapes.map((s) => s.group).filter(Boolean));
  for (const [k, st] of (spec.steps ?? []).entries()) {
    checkText(`${tag} step ${k + 1}`, st.label);
    ok(st.highlight.length > 0, `${tag} step ${k + 1}: highlights nothing`);
    for (const h of st.highlight) ok(byId[h] || groups.has(h), `${tag} step ${k + 1}: unknown shape id or group "${h}"`);
  }
  if (spec.corridor) checkCorridor(spec, tag, byId);
  if (spec.blockTask) checkBlockTask(spec, tag, byId);
  if (spec.cartPole) {
    const cp = spec.cartPole;
    const [axis, force, pole, theta] = [cp.axis, cp.force, cp.pole, cp.theta].map((id) => byId[id]);
    ok(axis && force && pole && theta, `${tag}: cartPole names missing shapes`);
    if (axis && force && pole && theta) {
      // the model: run cartpole() from lqr_sim.py
      const py = [
        "import json, sys",
        `sys.path.insert(0, ${JSON.stringify(join(root, "tools/sim/models"))})`,
        "import lqr_sim as s",
        "x = [0.0, 0.0, 0.0, 0.0]",
        "for _ in range(100): x = s.cartpole(x, 1.0)",  // 0.1 s of +1 N from upright
        "y = [0.0, 0.0, 0.05, 0.0]",
        "for _ in range(10): y = s.cartpole(y, 0.0)",   // 10 ms leaning +0.05 rad, no force
        "print(json.dumps({'forceCart': x[1], 'forceTheta': x[2], 'leanTheta': y[2] - 0.05, 'leanCart': y[1]}))",
      ].join("\n");
      const r = JSON.parse(execFileSync("python3", ["-c", py], { encoding: "utf8" }));
      ok(r.forceCart > 0 && r.forceTheta < 0, `${tag}: lqr_sim.cartpole: +F should move the cart +x and make theta negative (${JSON.stringify(r)})`);
      ok(r.leanTheta > 0 && r.leanCart < 0, `${tag}: lqr_sim.cartpole: +theta should grow under gravity and push the cart -x (${JSON.stringify(r)})`);
      // so +theta leans to the side a positive force tips the pole away from, i.e. towards +F and +x
      const sx = Math.sign(axis.to[0] - axis.from[0]);
      ok(sx !== 0 && axis.to[1] === axis.from[1] && axis.arrow, `${tag}: the x axis must be a horizontal arrow`);
      ok(Math.sign(force.to[0] - force.from[0]) === sx && force.arrow, `${tag}: +F must point along +x`);
      const lean = Math.sign(pole.to[0] - pole.from[0]);
      ok(pole.from[0] === cp.pivot[0] && pole.from[1] === cp.pivot[1] && pole.to[1] < pole.from[1], `${tag}: the pole must stand up from the pivot`);
      ok(lean === sx, `${tag}: the pole is drawn leaning ${lean > 0 ? "right" : "left"}, but +theta (labelled) leans towards +x`);
      ok(theta.at[0] === cp.pivot[0] && theta.at[1] === cp.pivot[1] && theta.from === 0 && Math.sign(theta.to) === sx && theta.arrow, `${tag}: the theta arc must start at upright and turn towards +x`);
      const deg = (Math.atan2(pole.to[0] - pole.from[0], pole.from[1] - pole.to[1]) * 180) / Math.PI;
      ok(Math.abs(deg - theta.to) < 0.5, `${tag}: theta arc ends at ${theta.to} deg, the pole leans ${deg.toFixed(1)} deg`);
      // the labels that name the positive directions: exactly "+x", "+F", "+θ" in both languages, at their shapes
      const near = (id, want, [px, py], maxD) => {
        const t = byId[id];
        ok(t && t.type === "text", `${tag}: cartPole label ${id} missing`);
        if (!t) return;
        for (const v of variants(t.label)) ok(v === want, `${tag}: label ${id} reads "${v}"; the model's positive direction is "${want}"`);
        const d = Math.hypot(t.at[0] - px, t.at[1] - py);
        ok(d <= maxD, `${tag}: label ${id} is ${d.toFixed(0)} units from its shape (max ${maxD})`);
      };
      near(cp.labels.axis, "+x", axis.to, 20);
      near(cp.labels.force, "+F", [(force.from[0] + force.to[0]) / 2, force.from[1]], 20);
      near(cp.labels.theta, "+θ", geoPolar(theta.at, theta.r, theta.to / 2), 30);
      if (r.forceTheta < 0) console.log(`model ${spec.id}: +1 N for 0.1 s -> cart ${r.forceCart.toFixed(3)} m/s, theta ${r.forceTheta.toFixed(4)} rad; drawn +theta leans to +x`);
    }
  }
  checkNumbers(spec, tag);
}

/**
 * Behaviour-cloning corridor (bc_reach.py): the corridor constants must be bc_reach's, the walls polyline must be the
 * corridor outline drawn through `map`, the success run must stay inside and end within the success radius, and the
 * failed run must stay inside until it leaves through the goal-end wall, never within the success radius.
 */
function checkCorridor(spec, tag, byId) {
  const c = spec.corridor, { x0, y0, s } = c.map;
  const py = [
    "import json, sys",
    `sys.path.insert(0, ${JSON.stringify(join(root, "examples/month-6/behaviour-cloning"))})`,
    "import bc_reach as b",
    "print(json.dumps({'corner': b.CORNER, 'goal': b.GOAL, 'hw': b.HALF_WIDTH, 'start': b.START}))",
  ].join("\n");
  const m = JSON.parse(execFileSync("python3", ["-c", py], { encoding: "utf8" }));
  const same = (a, b) => a[0] === b[0] && a[1] === b[1];
  ok(same(c.corner, m.corner) && same(c.goal, m.goal) && c.halfWidth === m.hw && same(m.start, [0, 0]),
    `${tag}: corridor ${JSON.stringify([c.corner, c.goal, c.halfWidth])} is not bc_reach.py's ${JSON.stringify([m.corner, m.goal, m.hw])}`);
  const hw = m.hw, [cx] = m.corner, [gx, gy] = m.goal;
  const toM = ([X, Y]) => [(X - x0) / s, (y0 - Y) / s];
  const toV = ([x, y]) => [x0 + s * x, y0 - s * y];
  const E = 0.001; // drawn points are rounded to 0.1 units (< 0.5 mm)
  // bc_reach.in_corridor, rebuilt here
  const inC = ([x, y]) => (x >= -hw - E && x <= cx + hw + E && Math.abs(y) <= hw + E) || (Math.abs(x - gx) <= hw + E && y >= -hw - E && y <= gy + hw + E);
  const walls = byId[c.walls], want = [[-hw, -hw], [cx + hw, -hw], [gx + hw, gy + hw], [gx - hw, gy + hw], [cx - hw, hw], [-hw, hw], [-hw, -hw]].map(toV);
  ok(walls && walls.type === "polyline" && walls.pts.length === want.length && walls.pts.every((p, i) => Math.hypot(p[0] - want[i][0], p[1] - want[i][1]) < 0.06),
    `${tag}: walls ${JSON.stringify(walls?.pts)} are not the corridor outline ${JSON.stringify(want.map((p) => p.map((v) => +v.toFixed(1))))}`);
  const run = (id) => { const r = byId[id]; ok(r && r.type === "polyline", `${tag}: corridor run ${id} missing`); return r ? r.pts.map(toM) : []; };
  const dGoal = (p) => Math.hypot(p[0] - gx, p[1] - gy);
  const okp = run(c.success);
  if (okp.length) {
    const out = okp.filter((p) => !inC(p));
    ok(out.length === 0, `${tag}: success run leaves the corridor at ${JSON.stringify(out[0])}`);
    ok(dGoal(okp.at(-1)) <= c.goalRadius + E, `${tag}: success run ends ${(dGoal(okp.at(-1)) * 100).toFixed(1)} cm from the goal (needs ${c.goalRadius * 100} cm)`);
  }
  const bad = run(c.fail);
  if (bad.length) {
    const out = bad.slice(0, -1).filter((p) => !inC(p));
    ok(out.length === 0, `${tag}: failed run leaves the corridor early at ${JSON.stringify(out[0])}`);
    const end = bad.at(-1), before = failed;
    ok(!inC(end) && end[1] > gy + hw && Math.abs(end[0] - gx) <= hw + 0.05, `${tag}: failed run should end past the goal-end wall, ends at ${JSON.stringify(end.map((v) => +v.toFixed(3)))}`);
    const closest = Math.min(...bad.map(dGoal));
    ok(closest > c.goalRadius, `${tag}: failed run comes within ${(closest * 100).toFixed(1)} cm of the goal, which would be a success`);
    if (failed === before) console.log(`model ${spec.id}: walls from bc_reach.py; success run inside, ends ${(dGoal(okp.at(-1)) * 100).toFixed(1)} cm from goal; failed run exits the end wall, closest ${(closest * 100).toFixed(1)} cm`);
  }
}

/**
 * multimodal.py's block task: block, goal, start, fork and waypoints must be where multimodal.py puts them; the 10
 * demo arrows must start near `at`; the drawn mean arrow must be the mean of the drawn demo arrows (the averaging
 * policy) and its ray must continue straight on to the block's near face, between its corners.
 */
function checkBlockTask(spec, tag, byId) {
  const b = spec.blockTask, { x0, y0, s } = b.map;
  const py = [
    "import json, re, sys",
    `sys.path.insert(0, ${JSON.stringify(join(root, "examples/month-6/act-diffusion"))})`,
    "import inspect, multimodal as m",
    "w = re.search(r'toward\\(p, \\(([\\d.]+) \\* side, ([\\d.]+)\\)\\)', inspect.getsource(m.expert))",
    "print(json.dumps({'goal': m.GOAL, 'by': m.BLOCK_Y, 'half': m.HALF, 'fork': m.FORK_Y, 'step': m.STEP, 'way': [float(w[1]), float(w[2])]}))",
  ].join("\n");
  const m = JSON.parse(execFileSync("python3", ["-c", py], { encoding: "utf8" }));
  const V = ([x, y]) => [x0 + s * x, y0 - s * y];
  const near = (p, q, tol = 0.06) => Math.hypot(p[0] - q[0], p[1] - q[1]) <= tol;
  const get = (id, type) => { const sh = byId[id]; ok(sh && sh.type === type, `${tag}: blockTask ${id} must be a ${type}`); return sh && sh.type === type ? sh : null; };
  const before = failed;
  const blk = get(b.block, "rect");
  if (blk) {
    ok(near(blk.at, V([-m.half, m.by + m.half])) && Math.abs(blk.size[0] - 2 * m.half * s) <= 0.06 && Math.abs(blk.size[1] - 2 * m.half * s) <= 0.06,
      `${tag}: block drawn at ${JSON.stringify(blk.at)} size ${JSON.stringify(blk.size)}, multimodal.py's is centre (0, ${m.by}) side ${2 * m.half} m`);
  }
  const g = get(b.goal, "circle");
  if (g) ok(near(g.at, V(m.goal)) && Math.abs(g.r - 0.05 * s) <= 0.06, `${tag}: goal circle is not GOAL with the 0.05 m success radius`);
  const st = get(b.start, "circle"), fk = get(b.fork, "circle");
  if (st) ok(near(st.at, V([0, 0])), `${tag}: start is not at (0, 0)`);
  if (fk) ok(near(fk.at, V([0, m.fork])), `${tag}: fork is not at (0, FORK_Y = ${m.fork})`);
  b.waypoints.forEach((id, k) => { const w = get(id, "circle"); if (w) ok(near(w.at, V([(k ? 1 : -1) * m.way[0], m.way[1]])), `${tag}: waypoint ${id} is not expert()'s (${k ? "+" : "-"}${m.way[0]}, ${m.way[1]})`); });
  const arrows = b.demos.map((id) => get(id, "line")).filter(Boolean);
  ok(arrows.length === b.demos.length && arrows.every((a) => a.arrow && near(a.from, V(b.at), 0.02 * s)), `${tag}: demo arrows must be arrows starting within 2 cm of (${b.at})`);
  for (const a of arrows) {
    const len = Math.hypot(a.to[0] - a.from[0], a.to[1] - a.from[1]) / s / b.arrowScale;
    ok(len <= m.step + 0.001, `${tag}: a demo arrow is ${(len * 100).toFixed(1)} cm long, more than STEP`);
  }
  const mean = get(b.mean, "line"), ray = get(b.meanRay, "line");
  if (mean && arrows.length) {
    const avg = [0, 1].map((i) => arrows.reduce((t, a) => t + (a.to[i] - a.from[i]), 0) / arrows.length);
    const d = [mean.to[0] - mean.from[0], mean.to[1] - mean.from[1]];
    ok(mean.arrow && near(mean.from, V(b.at)) && near(d, avg, 0.3), `${tag}: mean arrow ${JSON.stringify(d.map((v) => +v.toFixed(1)))} is not the mean of the demo arrows ${JSON.stringify(avg.map((v) => +v.toFixed(1)))}`);
    if (ray) {
      const cross = (ray.to[0] - mean.from[0]) * d[1] - (ray.to[1] - mean.from[1]) * d[0];
      const off = Math.abs(cross) / Math.hypot(...d);
      ok(near(ray.from, mean.to) && off <= 0.5, `${tag}: mean ray does not continue the mean arrow (${off.toFixed(1)} units off its line)`);
      const [hx, hy] = [(ray.to[0] - x0) / s, (y0 - ray.to[1]) / s];
      ok(Math.abs(hy - (m.by - m.half)) <= 0.001 && Math.abs(hx) < m.half, `${tag}: mean ray ends at (${hx.toFixed(3)}, ${hy.toFixed(3)}), not on the block's near face`);
      if (failed === before) console.log(`model ${spec.id}: block, goal, fork, waypoints from multimodal.py; mean of ${arrows.length} demo arrows meets the block face at x = ${(hx * 100).toFixed(1)} cm`);
    }
  }
}

// Spec files are plain data; the only imports allowed are types and JSON data files, inlined here.
const inlineJson = (src) =>
  src.replace(/^import (\w+) from "(\.\.?\/[^"]+\.json)";$/gm, (_, name, rel) => `const ${name} = ${readFileSync(join(specDir, rel), "utf8")};`);

// Data files: each JSON under src/lib/diagrams/data names the script that writes it; re-run and compare.
const dataDir = join(root, "src/lib/diagrams/data");
for (const f of existsSync(dataDir) ? readdirSync(dataDir).filter((f) => f.endsWith(".json")) : []) {
  const text = readFileSync(join(dataDir, f), "utf8");
  const script = JSON.parse(text).source;
  ok(typeof script === "string" && existsSync(join(root, script)), `data/${f}: "source" must name the script that writes it`);
  if (!script) continue;
  const out = execFileSync("python3", [join(root, script)], { encoding: "utf8" });
  ok(out === text, `data/${f} differs from the output of ${script} (re-run: python3 ${script} > src/lib/diagrams/data/${f})`);
}

const specs = [];
for (const f of readdirSync(specDir).filter((f) => f.endsWith(".ts"))) {
  const mod = await import(dataUrl(transpile(inlineJson(readFileSync(join(specDir, f), "utf8")))));
  for (const [name, v] of Object.entries(mod)) if (v && typeof v === "object" && v.kind) specs.push({ file: f, name, spec: v });
}
const index = readFileSync(join(root, "src/lib/diagrams/index.ts"), "utf8");
const ids = new Set();

for (const { file, name, spec } of specs) {
  const tag = `${spec.id} (${file}:${name})`;
  ok(!ids.has(spec.id), `${tag}: duplicate id`);
  ids.add(spec.id);
  ok(new RegExp(`\\[${name}\\.id\\]: ${name}`).test(index), `${tag}: not registered in src/lib/diagrams/index.ts`);
  checkText(`${tag} title`, spec.title);
  checkText(`${tag} caption`, spec.caption);
  for (const src of spec.sources) ok(existsSync(join(root, src)), `${tag}: source ${src} does not exist`);
  if (spec.kind === "circuit") checkCircuit(spec, tag);
  else if (spec.kind === "timing") checkTiming(spec, tag);
  else if (spec.kind === "bytes") checkBytes(spec, tag);
  else if (spec.kind === "poseGraph") checkPoseGraph(spec, tag);
  else if (spec.kind === "geo") checkGeo(spec, tag);
  else {
    const nodeIds = new Set(spec.nodes.map((n) => n.id));
    const edgeIds = new Set(spec.edges.map((e) => e.id));
    for (const n of spec.nodes) { checkText(`${tag} node ${n.id}`, n.label, n); checkText(`${tag} node ${n.id} sub`, n.sub, { mono: n.subMono }); }
    for (const e of spec.edges) checkText(`${tag} edge ${e.id}`, e.label, e);
    for (const [k, s] of (spec.steps ?? []).entries()) {
      checkText(`${tag} step ${k + 1}`, s.label);
      for (const h of s.highlight) ok(nodeIds.has(h) || edgeIds.has(h), `${tag} step ${k + 1}: unknown id "${h}"`);
    }
    if (spec.kind === "stateMachine") ok(nodeIds.has(spec.initial), `${tag}: initial state "${spec.initial}" missing`);
    checkScript(spec, tag);
    checkBindings(spec, tag, nodeIds, edgeIds);
    checkFlows(spec, tag);

    for (const which of ["wide", "narrow"]) {
      const L = spec.layouts[which];
      const lt = `${tag} ${which}`;
      if (which === "narrow") ok(L.w <= NARROW_MAX, `${lt}: width ${L.w} > ${NARROW_MAX} (text would render below ${MIN_PX} px on a 390 px phone)`);
      else ok(L.w <= WIDE_MAX, `${lt}: width ${L.w} > ${WIDE_MAX} (text would render below ${MIN_PX} px in the ${WIDE_BOX_PX} px box)`);
      const inside = (x, y, what) => ok(x >= 0 && y >= 0 && x <= L.w && y <= L.h, `${lt}: ${what} at (${x}, ${y}) is outside ${L.w}x${L.h}`);
      for (const n of spec.nodes) {
        const r = L.nodes[n.id];
        ok(r, `${lt}: node ${n.id} has no position`);
        if (!r) continue;
        const [x, y, w, h] = r;
        inside(x, y, `node ${n.id}`); inside(x + w, y + h, `node ${n.id}`);
        const shape = n.shape ?? (spec.kind === "stateMachine" ? "state" : "box");
        const room = shape === "state" ? w - h / 2 : shape === "text" ? w + 4 : w - 8;
        for (const t of variants(n.label)) ok(textWidth(t, FONT) <= room, `${lt}: node ${n.id} label "${t}" (${textWidth(t, FONT).toFixed(0)}) wider than ${room}`);
        for (const t of variants(n.sub)) {
          for (const line of lines(t)) ok(textWidth(line, SUB) <= room, `${lt}: node ${n.id} sub "${line}" (${textWidth(line, SUB).toFixed(0)}) wider than ${room}`);
          // same vertical placement as BlockDiagram.tsx: label baseline, then sub lines below it
          if (shape === "box" || shape === "state" || shape === "file") {
            const extra = (lines(t).length - 1) * (SUB + 2.5);
            const ly = y + h / 2 - 2 - extra / 2;
            const lastBase = ly + SUB + 3 + extra;
            ok(ly - FONT * 0.8 >= y && lastBase + 3 <= y + h, `${lt}: node ${n.id} label + ${lines(t).length} sub line(s) do not fit height ${h}`);
          }
        }
      }
      for (const e of spec.edges) {
        const g = L.edges[e.id];
        ok(g, `${lt}: edge ${e.id} has no geometry`);
        if (!g) continue;
        for (const [x, y] of g.pts) inside(x, y, `edge ${e.id} point`);
        if (e.label) {
          ok(g.label, `${lt}: edge ${e.id} label has no position`);
          if (!g.label) continue;
          for (const t of variants(e.label)) {
            lines(t).forEach((line, k) => {
              const w = textWidth(line, SUB);
              const a = g.anchor ?? "middle";
              const x0 = a === "start" ? g.label[0] : a === "end" ? g.label[0] - w : g.label[0] - w / 2;
              const yb = g.label[1] + k * (SUB + 2.5);
              inside(Math.floor(x0), Math.floor(yb - SUB), `edge ${e.id} label "${line}"`);
              inside(Math.ceil(x0 + w), Math.ceil(yb + 3), `edge ${e.id} label "${line}"`);
            });
          }
        }
      }
    }
  }

  for (const fact of spec.facts) {
    const p = join(root, fact.file);
    if (!existsSync(p)) { fail(`${tag}: fact file ${fact.file} missing`); continue; }
    const hit = new RegExp(fact.pattern, "m").test(readFileSync(p, "utf8"));
    ok(hit, `${tag}: fact not found in ${fact.file}: /${fact.pattern}/ (${fact.note})`);
    if (hit) console.log(`same  ${spec.id}: ${fact.note}  [${fact.file}]`);
  }
}

